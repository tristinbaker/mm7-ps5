#!/usr/bin/env python3
"""Writes a C source that logs the title's system imports that are null at run time.

    make-import-report.py <import list> <output.c>

Some functions the SDK's stub libraries list aren't there for a native title (getcwd and pathconf on firmware
13.60), so the import stays null and the first call jumps to address 0, which scripts/check-imports.sh can't
see. The generated constructor checks every import's address at startup and writes the null ones to the kernel
log, before anything can call them. The import list is one symbol per line, from the previous link.
"""
import re
import sys

names = []
for line in open(sys.argv[1]):
    name = line.strip()
    # sceKernelDebugOutText does the reporting (so it isn't null), and is declared as a function below.
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) and name != "sceKernelDebugOutText":
        names.append(name)

with open(sys.argv[2], "w") as out:
    out.write("// Generated by scripts/make-import-report.py, see there.\n")
    # Every import is declared as a char array, only its address matters.
    out.write("int sceKernelDebugOutText(int channel, const char *text);\n\n")
    # Declared under other C names, bound to the symbol with an asm label: many are C library functions that the
    # compiler already knows as functions.
    for i, name in enumerate(names):
        out.write(f'extern char import{i}[] __asm__("{name}") __attribute__((weak));\n')
    out.write("\nstatic const struct { const char *name; const void *address; } imports[] = {\n")
    for i, name in enumerate(names):
        out.write(f'    {{"{name}", import{i}}},\n')
    out.write("    {0, 0},\n};\n\n")
    out.write("""__attribute__((constructor(101))) static void reportNullImports(void) {
    int nulls = 0;
    for (int i = 0; imports[i].name; i++) {
        if (imports[i].address)
            continue;
        sceKernelDebugOutText(0, "[mm-ps5] null import: ");
        sceKernelDebugOutText(0, imports[i].name);
        sceKernelDebugOutText(0, "\\n");
        nulls++;
    }
    if (!nulls)
        sceKernelDebugOutText(0, "[mm-ps5] no null imports\\n");
}
""")
print(f"{sys.argv[2]}: {len(names)} imports")
